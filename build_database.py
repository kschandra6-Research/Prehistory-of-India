# 2. Write SQLite Database
if os.path.exists(db_path):
    os.remove(db_path)

conn = sqlite3.connect(db_path)
cur = conn.cursor()

create_table_sql = """
CREATE TABLE IF NOT EXISTS prehistoric_sites (
    site_id INTEGER PRIMARY KEY AUTOINCREMENT,
    period TEXT NOT NULL,
    cultural_tradition TEXT,
    site_name TEXT NOT NULL,
    alternative_names TEXT,
    country TEXT NOT NULL,
    state_province TEXT NOT NULL,
    district TEXT,
    river_basin TEXT,
    latitude REAL NOT NULL,
    longitude REAL NOT NULL,
    elevation_approx_m INTEGER,
    excavator_discoverer TEXT,
    year_of_discovery TEXT,
    excavation_seasons TEXT,
    tool_typology TEXT,
    length_min_mm REAL,
    length_max_mm REAL,
    width_min_mm REAL,
    width_max_mm REAL,
    thickness_min_mm REAL,
    thickness_max_mm REAL,
    primary_raw_materials TEXT,
    typical_usage TEXT,
    associated_features TEXT,
    visual_link_archive TEXT,
    key_references TEXT
);
"""
cur.execute(create_table_sql)

# Create Spatial & Analytical Indexes
cur.execute("CREATE INDEX idx_period ON prehistoric_sites(period);")
cur.execute("CREATE INDEX idx_country_state ON prehistoric_sites(country, state_province);")
cur.execute("CREATE INDEX idx_spatial_coords ON prehistoric_sites(latitude, longitude);")

# Insert Rows
insert_sql = f"""
INSERT INTO prehistoric_sites (
    {", ".join(fieldnames)}
) VALUES ({", ".join(["?" for _ in fieldnames])})
"""

for row in data:
    cur.execute(insert_sql, [row[f] for f in fieldnames])

# Create Analytical Views
cur.execute("""
CREATE VIEW view_period_summary AS
SELECT 
    period,
    COUNT(*) AS site_count,
    ROUND(AVG(length_max_mm), 1) AS avg_max_length_mm,
    ROUND(AVG(width_max_mm), 1) AS avg_max_width_mm,
    ROUND(AVG(thickness_max_mm), 1) AS avg_max_thickness_mm,
    MIN(latitude) AS min_lat,
    MAX(latitude) AS max_lat,
    MIN(longitude) AS min_lon,
    MAX(longitude) AS max_lon
FROM prehistoric_sites
GROUP BY period
ORDER BY site_count DESC;
""")

cur.execute("""
CREATE VIEW view_gis_export AS
SELECT 
    site_id,
    site_name,
    period,
    cultural_tradition,
    state_province,
    country,
    latitude,
    longitude,
    elevation_approx_m,
    excavator_discoverer,
    year_of_discovery,
    primary_raw_materials,
    tool_typology
FROM prehistoric_sites;
""")

